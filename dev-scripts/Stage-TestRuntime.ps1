<#
.SYNOPSIS
    Phase 2B dev/test helper ONLY - not a shipping architecture component. Manually stages
    C:\ProgramData\Elkjop\Toolkit\Runtime\ (SupportTool.exe, config.json, session.json) so the
    Support Tool session/reboot/runtime lifecycle can be exercised before service.exe (Phase 3)
    or Account Setup staging (Phase 4) exist to do this for real.

.DESCRIPTION
    Copies a published Support Tool exe and an existing config.json into the Runtime folder, and
    writes a session.json matching the requested test scenario. See
    dev-scripts\PHASE-2B-MANUAL-TESTS.md for the exact Test A-G scenarios this supports.

.PARAMETER SourceExePath
    Path to an already-published Support Tool-<arch>.exe (e.g. from
    "Support Tool\bin\Release\net10.0-windows\win-x64\Support Tool-x64.exe", or a deployed USB
    copy under "...\Elkjop Toolkit\Support Tool\").

.PARAMETER SourceConfigPath
    Path to an existing config.json to stage (e.g. a deployed USB copy). Not generated by this
    script - Support Tool's own ConfigService.CreateDefaultConfig() is the source of truth for
    default catalog content, and staging a real file exercises the real strict-load path.

.PARAMETER Workflow
    'Setup' or 'Service'.

.PARAMETER Stage
    'WindowsUpdate', 'Install', 'Debloat', 'Customization', or 'Finish'. Default: WindowsUpdate.

.PARAMETER ResumeRequired
    Switch. Sets session.json's ResumeRequired to true.

.PARAMETER FirstDesktopActionsCompleted
    Switch. Explicitly sets FirstDesktopActionsCompleted. If omitted, defaults to false for
    Setup and true for Service, matching how Account Setup / Service Launcher will eventually
    write the initial session (see Toolkit.Shared.SessionState's own remarks).

.PARAMETER CreateInitialTask
    Switch. Also registers the "Elkjop Toolkit Resume" scheduled task via the simple
    /sc onlogon flag form (NOT Toolkit.Shared.ScheduledTaskXmlBuilder's XML form - that form
    exists specifically to bind correctly under FirstLogonCommands' SYSTEM context, which
    doesn't apply here; this script runs interactively as the real technician/dev account, so
    the simpler flag form binds correctly and is good enough for exercising Support Tool's own
    lifecycle logic). Use this to reproduce Test C/D's "task already exists at first launch"
    starting condition, which in production Account Setup would have created.

.PARAMETER Clean
    Switch. Deletes any existing Runtime folder (and the resume task, if present) before staging.

.EXAMPLE
    .\Stage-TestRuntime.ps1 -SourceExePath "..\Support Tool\bin\Release\net10.0-windows\win-x64\Support Tool-x64.exe" `
        -SourceConfigPath "X:\Elkjop Toolkit\Support Tool\config.json" `
        -Workflow Setup -Stage WindowsUpdate -CreateInitialTask -Clean

.EXAMPLE
    .\Stage-TestRuntime.ps1 -SourceExePath "...\Support Tool-x64.exe" -SourceConfigPath "...\config.json" `
        -Workflow Service -ResumeRequired -Stage WindowsUpdate -Clean
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string]$SourceExePath,
    [Parameter(Mandatory)] [string]$SourceConfigPath,
    [Parameter(Mandatory)] [ValidateSet('Setup', 'Service')] [string]$Workflow,
    [ValidateSet('WindowsUpdate', 'Install', 'Debloat', 'Customization', 'Finish')] [string]$Stage = 'WindowsUpdate',
    [switch]$ResumeRequired,
    [Nullable[bool]]$FirstDesktopActionsCompleted = $null,
    [switch]$CreateInitialTask,
    [switch]$Clean
)

$ErrorActionPreference = 'Stop'

$RuntimeFolder = 'C:\ProgramData\Elkjop\Toolkit\Runtime'
$TaskName = 'Elkjop Toolkit Resume'

if (-not (Test-Path $SourceExePath)) { throw "SourceExePath not found: $SourceExePath" }
if (-not (Test-Path $SourceConfigPath)) { throw "SourceConfigPath not found: $SourceConfigPath" }

if ($Clean) {
    Write-Host "Cleaning existing Runtime folder and resume task..." -ForegroundColor Yellow
    schtasks /delete /tn $TaskName /f 2>$null | Out-Null
    if (Test-Path $RuntimeFolder) {
        Remove-Item $RuntimeFolder -Recurse -Force
    }
}

New-Item -ItemType Directory -Path $RuntimeFolder -Force | Out-Null

Copy-Item $SourceExePath (Join-Path $RuntimeFolder 'SupportTool.exe') -Force
Copy-Item $SourceConfigPath (Join-Path $RuntimeFolder 'config.json') -Force

if ($null -eq $FirstDesktopActionsCompleted) {
    $FirstDesktopActionsCompleted = ($Workflow -eq 'Service')
}

$session = [ordered]@{
    Workflow                    = $Workflow
    Stage                       = $Stage
    ResumeRequired              = [bool]$ResumeRequired
    FirstDesktopActionsCompleted = [bool]$FirstDesktopActionsCompleted
}

$sessionJson = $session | ConvertTo-Json
Set-Content -Path (Join-Path $RuntimeFolder 'session.json') -Value $sessionJson -Encoding utf8

if ($CreateInitialTask) {
    $exePath = Join-Path $RuntimeFolder 'SupportTool.exe'
    schtasks /create /tn $TaskName /tr "`"$exePath`"" /sc onlogon /rl highest /f | Out-Null
    Write-Host "Registered '$TaskName' (simple flag form - dev/test convenience only, see .DESCRIPTION)." -ForegroundColor Cyan
}

Write-Host ""
Write-Host "Staged Runtime at $RuntimeFolder :" -ForegroundColor Green
Get-ChildItem $RuntimeFolder | Format-Table Name, Length, LastWriteTime -AutoSize
Write-Host ""
Write-Host "session.json:" -ForegroundColor Green
Get-Content (Join-Path $RuntimeFolder 'session.json')
